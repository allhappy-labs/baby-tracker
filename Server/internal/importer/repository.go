package importer

import (
	"bytes"
	"context"
	"crypto/hmac"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"encoding/json"
	"strings"
	"time"

	"babytracker/server/internal/access"
	"babytracker/server/internal/protocol"
	"github.com/jackc/pgx/v5"
)

func (s *Service) binding(p access.Principal, family string, v session) []byte {
	raw, _ := json.Marshal([]any{s.info.InstanceID, s.info.RecoveryEpoch, family, v.id, p.AccountID, p.DeviceID, p.SessionID, p.SecurityRevision, v.revision, s.limits.SyncPageSize, s.limits.SyncPageBytes})
	h := sha256.Sum256(raw)
	return h[:]
}
func (s *Service) token(p access.Principal, family string, v session, last string) (string, error) {
	key := s.keys.Current
	if key.ID == "" || len(key.ID) > 64 || key.Secret == ([32]byte{}) {
		return "", code("service_unavailable")
	}
	raw := []byte{1, byte(len(key.ID))}
	raw = append(raw, key.ID...)
	raw = binary.BigEndian.AppendUint64(raw, v.revision)
	raw = binary.BigEndian.AppendUint64(raw, uint64(s.now().Add(time.Duration(s.limits.SyncPageTTLSeconds)*time.Second).Unix()))
	raw = append(raw, last...)
	raw = append(raw, s.binding(p, family, v)...)
	mac := hmac.New(sha256.New, key.Secret[:])
	mac.Write([]byte("baby-tracker-import-conflicts-v1\x00"))
	mac.Write(raw)
	raw = append(raw, mac.Sum(nil)...)
	return base64.RawURLEncoding.EncodeToString(raw), nil
}
func (s *Service) resume(p access.Principal, family string, v session, token string) (string, error) {
	if len(token) > 512 {
		return "", code("invalid_page_token")
	}
	raw, e := base64.RawURLEncoding.Strict().DecodeString(token)
	if e != nil || len(raw) < 2 || raw[0] != 1 {
		return "", code("invalid_page_token")
	}
	n := int(raw[1])
	if n < 1 || n > 64 || len(raw) != 2+n+16+36+32+32 {
		return "", code("invalid_page_token")
	}
	id := string(raw[2 : 2+n])
	key := s.keys.Current
	found := key.ID == id
	for _, k := range s.keys.Previous {
		if k.ID == id {
			key = k
			found = true
		}
	}
	if !found {
		return "", code("invalid_page_token")
	}
	mac := hmac.New(sha256.New, key.Secret[:])
	mac.Write([]byte("baby-tracker-import-conflicts-v1\x00"))
	mac.Write(raw[:len(raw)-32])
	if !hmac.Equal(raw[len(raw)-32:], mac.Sum(nil)) {
		return "", code("invalid_page_token")
	}
	revision := binary.BigEndian.Uint64(raw[2+n:])
	expires := binary.BigEndian.Uint64(raw[10+n:])
	bound := v
	bound.revision = revision
	if !bytes.Equal(raw[54+n:86+n], s.binding(p, family, bound)) {
		return "", code("invalid_page_token")
	}
	if revision != v.revision {
		return "", code("import_resolution_stale")
	}
	if uint64(s.now().Unix()) >= expires {
		return "", code("page_expired")
	}
	last := string(raw[18+n : 54+n])
	if !protocol.ValidUUID(last) {
		return "", code("invalid_page_token")
	}
	return last, nil
}

func (s *Service) response(ctx context.Context, tx pgx.Tx, p access.Principal, family string, v session, page *string, pending []conflict) (protocol.ImportResolveResponse, error) {
	out := protocol.ImportResolveResponse{ImportID: v.id, ResolverRevision: v.revision, NormalizationVersion: v.normalization, Mappings: []protocol.BabyMapping{}, Conflicts: []protocol.ImportConflict{}, MappingComplete: v.mapped, ManifestComplete: v.complete, NextChunkIndex: v.next, ConflictsComplete: true}
	last := ""
	if page != nil {
		var e error
		last, e = s.resume(p, family, v, *page)
		if e != nil {
			return out, e
		}
	}
	if v.mapped {
		rows, e := tx.Query(ctx, `SELECT local_baby_id::text,shared_baby_id::text FROM import_baby_mappings WHERE family_id=$1 AND import_id=$2 ORDER BY local_baby_id`, family, v.id)
		if e != nil {
			return out, e
		}
		for rows.Next() {
			var m protocol.BabyMapping
			if e = rows.Scan(&m.LocalBabyID, &m.SharedBabyID); e != nil {
				rows.Close()
				return out, e
			}
			out.Mappings = append(out.Mappings, m)
		}
		e = rows.Err()
		rows.Close()
		if e != nil {
			return out, e
		}
	}
	var count uint64
	e := tx.QueryRow(ctx, `SELECT count(*) FROM import_conflicts WHERE family_id=$1 AND import_id=$2 AND decision_choice IS NULL AND (NOT $3 OR record_id IS NOT NULL)`, family, v.id, v.mapped).Scan(&count)
	if e != nil {
		return out, e
	}
	// Only fetch one bounded page from retained conflicts. Pending conflicts are
	// generated by this transaction before its immutable chunk response exists.
	after := last
	if after == "" {
		after = "00000000-0000-0000-0000-000000000000"
	}
	rows, e := tx.Query(ctx, `SELECT conflict_id::text,kind,local_baby_id::text,record_id::text,candidate_baby_ids::text[],candidate_versions FROM import_conflicts WHERE family_id=$1 AND import_id=$2 AND decision_choice IS NULL AND (NOT $3 OR record_id IS NOT NULL) AND conflict_id>$4::uuid ORDER BY conflict_id LIMIT $5`, family, v.id, v.mapped, after, s.limits.SyncPageSize+1)
	if e != nil {
		return out, e
	}
	all := []conflict{}
	for rows.Next() {
		var c conflict
		if e = rows.Scan(&c.ConflictID, &c.Kind, &c.LocalBabyID, &c.RecordID, &c.CandidateBabyIDs, &c.CandidateVersions); e != nil {
			rows.Close()
			return out, e
		}
		all = append(all, c)
	}
	e = rows.Err()
	rows.Close()
	if e != nil {
		return out, e
	}
	byID := map[string]protocol.ImportConflict{}
	for _, c := range append(all, pending...) {
		if c.choice == nil && (!v.mapped || c.RecordID != nil) {
			byID[c.ConflictID] = c.ImportConflict
		}
	}
	conflicts := make([]protocol.ImportConflict, 0, len(byID))
	for _, c := range byID {
		conflicts = append(conflicts, c)
	}
	sortConflicts(conflicts)
	out.ConflictCount = count + uint64(len(pending))
	reserve := strings.Repeat("x", 512)
	for _, c := range conflicts {
		if c.ConflictID <= last {
			continue
		}
		out.Conflicts = append(out.Conflicts, c)
		out.NextConflictPageToken = &reserve
		raw, _ := json.Marshal(out)
		out.NextConflictPageToken = nil
		if len(out.Conflicts) > s.limits.SyncPageSize || len(raw) > s.limits.SyncPageBytes {
			out.Conflicts = out.Conflicts[:len(out.Conflicts)-1]
			if len(out.Conflicts) == 0 {
				return out, code("import_page_limit")
			}
			out.ConflictsComplete = false
			token, e := s.token(p, family, v, out.Conflicts[len(out.Conflicts)-1].ConflictID)
			if e != nil {
				return out, e
			}
			out.NextConflictPageToken = &token
			break
		}
	}
	raw, _ := json.Marshal(out)
	if len(raw) > s.limits.SyncPageBytes {
		return out, code("import_page_limit")
	}
	return out, nil
}
